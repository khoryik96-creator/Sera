function stripMarker(p) { return p.replace(/^\[\[speaker:[^\]]+\]\]/, ''); }
function chapterParts(text) {
  const re = /^## Chapter (\d+) — /gm;
  const heads = [...text.matchAll(re)];
  return heads.map((h,i)=>({chapter:Number(h[1]), start:h.index, end:heads[i+1]?.index ?? text.length}));
}

const byChapter = new Map();
for (const e of entries) {
  const a = byChapter.get(e[0]) || []; a.push(e); byChapter.set(e[0], a);
}
let added = 0;
for (const [file, original] of sources) {
  let text = original;
  const parts = chapterParts(text).reverse();
  for (const part of parts) {
    const list = byChapter.get(part.chapter); if (!list) continue;
    let section = text.slice(part.start, part.end);
    let paras = section.split(/\n{2,}/);
    for (const [, quote, speaker] of list) {
      const matches = [];
      for (let i=0;i<paras.length;i++) if (stripMarker(paras[i].trim()) === quote) matches.push(i);
      if (matches.length === 0) throw new Error(`Ch${part.chapter}: target not found: ${quote}`);
      if (matches.length > 1) continue; // repeated short line: leave for context-anchored pass
      const i = matches[0];
      const trimmed = paras[i].trim();
      const existing = trimmed.match(/^\[\[speaker:([^\]]+)\]\]/);
      if (existing) {
        if (existing[1] !== speaker) throw new Error(`Ch${part.chapter}: ${quote} already marked ${existing[1]}, expected ${speaker}`);
        continue;
      }
      paras[i] = paras[i].replace(quote, `[[speaker:${speaker}]]${quote}`);
      added++;
    }
    section = paras.join('\n\n');
    text = text.slice(0, part.start) + section + text.slice(part.end);
  }
  if (text !== original) await writeFile(`${dir}/${file}`, text);
}
console.log(`Added ${added} explicit Season 95 speaker markers.`);
